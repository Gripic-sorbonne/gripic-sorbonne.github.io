#!/bin/bash

# Stop execution if any command fails
set -e

# Store the repository root path
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

echo "========================================================"
echo "1. Entering scripts/ and converting Excel to CSV..."
cd "$REPO_ROOT/scripts"
python excel_to_csv.py
sleep 2

echo "========================================================"
echo "2. Completely cleaning the previous data directory..."
cd "$REPO_ROOT"
if [ -d "data" ]; then
    rm -rf data
    git add -A data
fi
sleep 2

echo "========================================================"
echo "3. Generating Markdown files from CSV..."
cd "$REPO_ROOT/scripts"
python init_files_from_csv.py

# Extended pause to ensure the filesystem has physically written and closed
# all .md and .webp files generated by Python
echo "Waiting 5 seconds for the disk to synchronize the files..."
sleep 5

echo "========================================================"
echo "4. Staging all new changes..."
cd "$REPO_ROOT"
git add -A
sleep 2

# Check whether there are any actual changes in the repository
if git diff-index --quiet HEAD --; then
    echo "No changes detected. Creating an empty commit to trigger a build..."
    git commit --allow-empty -m "trigger: re-run build"
else
    COMMIT_MSG="${1:-update data from Excel}"
    git commit -m "$COMMIT_MSG"
fi

# Brief pause before pushing to the remote repository
sleep 2

echo "========================================================"
echo "5. Pushing changes to GitHub..."
git push

echo "========================================================"
echo "Pipeline executed successfully with synchronization delays!"